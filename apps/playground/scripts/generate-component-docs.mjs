// Generates docs/components.md from the same catalog and lab registry the playground renders,
// so the written reference cannot drift from the Component Lab. CI fails if the output changes.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createServer } from 'vite';

const appRoot = resolve(import.meta.dirname, '..');
const repoRoot = resolve(appRoot, '../..');

const server = await createServer({
  root: appRoot,
  configFile: resolve(appRoot, 'vite.config.ts'),
  server: { middlewareMode: true, hmr: false },
  appType: 'custom',
  logLevel: 'error',
});

try {
  const { CATALOG, CATEGORIES, componentsInCategory, importLine } =
    await server.ssrLoadModule('/src/catalog/catalog.ts');
  const { REGISTRY } = await server.ssrLoadModule('/src/features/component-lab/registry.ts');

  const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
  // Escape HTML-like text in prose (e.g. "<button>") but leave `code spans` untouched.
  const prose = (s) =>
    String(s)
      .split(/(`[^`]*`)/)
      .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/>/g, '&gt;')))
      .join('');
  const out = [
    '# Component reference',
    '',
    '<!-- Generated by `pnpm docs:components` from apps/playground/src/catalog and the lab registry. Do not edit by hand. -->',
    '',
    'Every component is exported from `@toyo-ui/react` and needs `ToyoThemeProvider` from `@toyo-ui/theme` at the app root.',
    'The interactive version of this reference is the Component Lab (`pnpm dev`).',
    '',
  ];

  for (const category of CATEGORIES) {
    for (const id of componentsInCategory(category.id)) {
      const doc = CATALOG[id];
      out.push(
        `## ${doc.name}`,
        '',
        `**Status:** ${doc.status} · **Category:** ${category.label}`,
        '',
        prose(doc.purpose),
        '',
        '```tsx',
        importLine(id),
        '```',
        '',
        '### Usage',
        '',
        '```tsx',
        REGISTRY[id].code(REGISTRY[id].defaults).trimEnd(),
        '```',
        '',
        '### Props',
        '',
        '| Prop | Type | Default | Description |',
        '|---|---|---|---|',
        ...doc.props.map(
          (p) =>
            `| \`${p.name}\`${p.required ? ' (required)' : ''} | \`${cell(p.type)}\` | ${p.default ? `\`${cell(p.default)}\`` : '—'} | ${prose(cell(p.description))} |`,
        ),
        '',
        `**Variants and states:** ${doc.states.join(', ')}.`,
        '',
        '### API decisions',
        '',
        ...doc.apiDecisions.map((d) => `- ${prose(d)}`),
        '',
        '### Accessibility',
        '',
        ...doc.accessibility.map((a) => `- ${prose(a)}`),
        '',
        `### Test coverage (\`packages/react/src/${doc.name}.test.tsx\`)`,
        '',
        ...doc.testing.map((t) => `- ${prose(t)}`),
        '',
      );
    }
  }

  writeFileSync(resolve(repoRoot, 'docs/components.md'), out.join('\n'));
  console.log(`docs/components.md: ${Object.keys(CATALOG).length} components`);
} finally {
  await server.close();
}
